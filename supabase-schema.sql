-- 1. Create the consultations table in public schema
CREATE TABLE IF NOT EXISTS public.consultations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  full_name TEXT NOT NULL,
  country TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL DEFAULT '',
  treatment TEXT,
  city TEXT,
  message TEXT,
  source TEXT DEFAULT 'website',
  status TEXT DEFAULT 'new'
);

-- 2. Grant table and sequence permissions to public/anon/authenticated roles
GRANT ALL ON TABLE public.consultations TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;

-- 4. Create Policy: Allow public/anonymous visitors to insert consultation requests
DROP POLICY IF EXISTS "Allow anonymous patient inserts" ON public.consultations;
CREATE POLICY "Allow anonymous patient inserts" 
ON public.consultations 
FOR INSERT 
TO public, anon, authenticated
WITH CHECK (true);

-- 5. Create Policy: Allow reading consultations (coordinators / admins)
DROP POLICY IF EXISTS "Allow coordinators to view consultations" ON public.consultations;
CREATE POLICY "Allow coordinators to view consultations" 
ON public.consultations 
FOR SELECT 
TO public, anon, authenticated
USING (true);

-- 6. Reload PostgREST schema cache immediately
NOTIFY pgrst, 'reload schema';

-- 7. Verify table creation
SELECT * FROM public.consultations LIMIT 5;

