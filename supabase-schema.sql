-- 1. Ensure table exists with exact live columns
CREATE TABLE IF NOT EXISTS public.consultations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT NOT NULL,
  country TEXT NOT NULL,
  message TEXT
);

-- 2. Keep Row Level Security (RLS) ENABLED to protect patient confidentiality
ALTER TABLE public.consultations ENABLE ROW LEVEL SECURITY;

-- 3. Remove any previous conflicting policies
DROP POLICY IF EXISTS "Allow anonymous patient inserts" ON public.consultations;
DROP POLICY IF EXISTS "Allow anonymous patient consultation submissions" ON public.consultations;
DROP POLICY IF EXISTS "Allow public consultation submissions" ON public.consultations;
DROP POLICY IF EXISTS "Allow coordinators to view consultations" ON public.consultations;
DROP POLICY IF EXISTS "Allow staff to view consultations" ON public.consultations;
DROP POLICY IF EXISTS "Allow authenticated staff to view consultations" ON public.consultations;

-- 4. Create a NARROWLY SCOPED INSERT-ONLY policy for public/anonymous submissions
-- Only allows INSERT (no public SELECT, no UPDATE, no DELETE).
-- Strictly validates that name and phone are non-empty strings.
CREATE POLICY "Allow anonymous patient consultation submissions" 
ON public.consultations 
FOR INSERT 
TO anon, authenticated
WITH CHECK (
  length(trim(name)) > 0 AND 
  length(trim(phone)) > 0
);

-- 5. Create a RESTRICTED SELECT policy for authenticated coordinators / admins ONLY
-- Public/anonymous visitors CANNOT query or view submitted consultations.
CREATE POLICY "Allow authenticated staff to view consultations" 
ON public.consultations 
FOR SELECT 
TO authenticated
USING (true);

-- 6. Grant appropriate PostgreSQL role privileges
GRANT INSERT ON TABLE public.consultations TO anon, authenticated;
GRANT SELECT ON TABLE public.consultations TO authenticated;
GRANT ALL ON TABLE public.consultations TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 7. Notify PostgREST to reload the schema cache immediately
NOTIFY pgrst, 'reload schema';

-- 8. Verify the table and policies
SELECT * FROM public.consultations LIMIT 5;



