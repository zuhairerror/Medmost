-- 1. Create the consultations table
CREATE TABLE IF NOT EXISTS consultations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
  full_name TEXT NOT NULL,
  country TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL,
  treatment TEXT,
  city TEXT,
  message TEXT,
  source TEXT DEFAULT 'website',
  status TEXT DEFAULT 'new'
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE consultations ENABLE ROW LEVEL SECURITY;

-- 3. Create Policy: Allow public/anonymous visitors to insert consultation requests
DROP POLICY IF EXISTS "Allow anonymous patient inserts" ON consultations;
CREATE POLICY "Allow anonymous patient inserts" 
ON consultations 
FOR INSERT 
WITH CHECK (true);

-- 4. Create Policy: Allow authenticated coordinators / admins to view consultations
DROP POLICY IF EXISTS "Allow coordinators to view consultations" ON consultations;
CREATE POLICY "Allow coordinators to view consultations" 
ON consultations 
FOR SELECT 
USING (true);

-- Verify table creation
SELECT * FROM consultations LIMIT 5;
